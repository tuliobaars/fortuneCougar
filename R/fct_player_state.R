# ---------------------------------------------------------------------------
# state_player.R -- the global, reactive player session.
#
# One `player` object is created per browser session in the app server and
# handed to every module. It owns the coin balance and every metagame
# progression (XP/levels, Cougar Album cards, Star Market stars & avatars,
# Playtika Rewards points, Daily Dash missions, Monsterpedia captures,
# Wheel of Fun cooldowns, boosts and per-machine meters).
#
# Modules never modify `player$rv` directly for money: they call
#   player$debit(x) / player$credit(x)          -- coins
#   player$record(...)                          -- after every play
# and the state fans the event out to all progression systems.
# State is persisted to the browser's localStorage (see inst/app/www/casino.js).
# ---------------------------------------------------------------------------

SAVE_VERSION <- 1L

# @param store a storage backend from fc_storage() (plays are logged there)
player_state <- function(session = shiny::getDefaultReactiveDomain(), store = fc_storage("browser")) {
  rv <- shiny::reactiveValues(
    coins = START_COINS, xp = 0, level = 1L, stars = 25,
    vip_points = 0, vip_by_family = stats::setNames(rep(0, length(REWARD_FAMILIES)), names(REWARD_FAMILIES)),
    album = integer(0), sets_claimed = integer(0), album_claimed = FALSE,
    avatar = DEFAULT_AVATAR, avatars = DEFAULT_AVATAR,
    boosts = list(xp2 = 0L, win20 = 0L),
    wheel_hourly_at = 0, wheel_daily_on = "", vip_gift_on = "",
    dash = list(), dash_claimed = character(0),
    monster = list(), monster_claimed = character(0),
    stats = list(plays = 0, wagered = 0, won = 0, biggest = 0, biggest_game = "",
                 packs = 0, spins = 0, hands = 0),
    game_meta = list(), recent_pulls = character(0), feed = character(0),
    lucky = NULL, nav = NULL, restored = FALSE,
    name = "", track = track_new(), ask_name = NULL
  )

  send <- function(type, msg) {
    if (!is.null(session)) session$sendCustomMessage(type, msg)
  }

  self <- list(rv = rv, store = store)
  ident <- new.env(parent = emptyenv())
  ident$id <- NULL

  # Anonymous player id (generated by the browser, used as the database key).
  self$set_id <- function(id) ident$id <- id
  self$id <- function() ident$id

  # Player name (chosen at startup; unique per database).
  self$name <- function() shiny::isolate(rv$name)
  self$set_name <- function(name) rv$name <- as.character(name)

  # ---- play sessions ---------------------------------------------------------------
  # A session runs from loading a profile until the browser disconnects (or
  # the player switches profile). Finished sessions are kept in the track and
  # logged to the store.
  self$session_begin <- function(now = now_secs()) {
    ident$session <- list(t0 = now, balance = shiny::isolate(rv$coins), plays = shiny::isolate(rv$track$n))
    invisible(ident$session)
  }
  self$session <- function() ident$session
  self$session_end <- function(now = now_secs()) {
    s <- ident$session
    if (is.null(s)) return(invisible(NULL))
    ident$session <- NULL
    shiny::isolate({
      secs <- max(0, now - s$t0)
      plays <- rv$track$n - s$plays
      if (plays <= 0 && secs < 30) return(invisible(NULL))     # nothing worth keeping
      rv$track <- track_add_session(rv$track, s$t0, secs, plays, s$balance, rv$coins)
      if (!is.null(ident$id)) store$log_session(ident$id, s$t0, now, secs, s$balance, rv$coins, plays)
    })
    invisible(TRUE)
  }
  # Behaviour features for the classifier (NULL until enough plays).
  self$features <- function() stats_features(shiny::isolate(rv$track))

  # Save the profile: to the store (server-side backends) or to the browser's
  # localStorage. Unnamed profiles are not saved (a name is asked at startup).
  self$save <- function(snap = NULL) {
    id <- ident$id
    if (is.null(id)) return(invisible(FALSE))
    snap <- snap %||% shiny::isolate(self$snapshot())
    if (!nzchar(snap$name %||% "")) return(invisible(FALSE))
    if (store$server_side) {
      lang <- if (!is.null(session)) session$userData$fc_lang %||% "en" else "en"
      store$save_player(id, snap, lang, features = self$features())
    } else {
      send("fc_save", list(data = as.character(jsonlite::toJSON(snap, auto_unbox = TRUE, null = "null", digits = NA))))
    }
    invisible(TRUE)
  }
  # Tell the browser which player id to remember.
  self$send_id <- function(id = ident$id) send("fc_set_id", list(id = id))
  # Load a stored profile into this session. FALSE if missing / invalid.
  self$load <- function(id) {
    saved <- store$load_player(id)
    if (is.null(saved) || !isTRUE(self$restore(saved))) return(FALSE)
    ident$id <- id
    TRUE
  }
  # Ask the player for a name (mode "welcome" at startup, "switch" later).
  self$ask_name <- function(mode = "welcome") rv$ask_name <- list(mode = mode, nonce = stats::runif(1))

  # ---- notifications -----------------------------------------------------------
  self$toast <- function(title, body = "", kind = "info", icon = "") {
    send("fc_toast", list(title = title, body = body, kind = kind, icon = icon))
  }
  self$celebrate <- function(kind, amount = 0, title = "", subtitle = "", delay = 0) {
    send("fc_celebrate", list(kind = kind, amount = amount, title = title, subtitle = subtitle, delay = delay))
  }
  self$log <- function(txt) {
    rv$feed <- utils::head(c(paste(format(Sys.time(), "%H:%M"), txt), shiny::isolate(rv$feed)), 30)
  }

  # ---- coins ------------------------------------------------------------------------
  self$coins <- function() shiny::isolate(rv$coins)
  self$can_afford <- function(x) shiny::isolate(rv$coins) >= x
  self$debit <- function(x) {
    x <- round(x)
    if (x <= 0) return(TRUE)
    cur <- shiny::isolate(rv$coins)
    if (cur < x) return(FALSE)
    rv$coins <- cur - x
    TRUE
  }
  self$credit <- function(x) {
    x <- round(x)
    if (x > 0) rv$coins <- shiny::isolate(rv$coins) + x
    invisible(x)
  }
  self$max_bet_index <- function() max_bet_index(shiny::isolate(rv$level))

  # ---- boosts ---------------------------------------------------------------------------
  # Apply the Win Booster (+20% on slot wins) and count it down.
  self$boost_slot_win <- function(win) {
    b <- shiny::isolate(rv$boosts)
    if ((b$win20 %||% 0) > 0) {
      b$win20 <- b$win20 - 1L; rv$boosts <- b
      return(round(win * 1.2))
    }
    win
  }

  # ---- navigation -----------------------------------------------------------------------
  self$go <- function(tab, game = NULL) {
    rv$nav <- list(tab = tab, game = game, nonce = stats::runif(1))
  }

  # ---- per-machine persistent meters ------------------------------------------------------
  self$get_meta <- function(id) shiny::isolate(rv$game_meta[[id]]) %||% list()
  self$set_meta <- function(id, gs) {
    keep <- Filter(function(v) (is.numeric(v) || is.integer(v)) && length(v) == 1 && !is.na(v), gs)
    gm <- shiny::isolate(rv$game_meta); gm[[id]] <- keep; rv$game_meta <- gm
  }

  # ---- album / packs -------------------------------------------------------------------------
  self$award_pack <- function(tier, source = "") {
    owned <- shiny::isolate(rv$album)
    p <- open_pack(tier, owned)
    for (id in p$ids) owned[id] <- (if (is.na(owned[id])) 0L else owned[id]) + 1L
    rv$album <- owned
    rv$recent_pulls <- utils::head(c(rev(p$ids), shiny::isolate(rv$recent_pulls)), 24)
    st <- shiny::isolate(rv$stats); st$packs <- st$packs + 1; rv$stats <- st
    n_new <- sum(p$new)
    glyphs <- paste(ALBUM_CARDS$glyph[match(p$ids, ALBUM_CARDS$id)], collapse = " ")
    self$toast(sprintf("%s %s%s", PACKS[[tier]]$icon, tr(PACKS[[tier]]$name), if (nzchar(source)) paste(" -", tr(source)) else ""),
               paste(glyphs, "&nbsp;", trn(length(p$ids), "%d card, %d new", "%d cards, %d new", length(p$ids), n_new)),
               kind = "pack")
    self$log(trn(n_new, "Opened %s (%d new card)", "Opened %s (%d new cards)", tr(PACKS[[tier]]$name), n_new))
    if (length(p$lucky)) {
      # never overwrite an unfinished Lucky Cards game
      if (is.null(shiny::isolate(rv$lucky))) rv$lucky <- make_lucky_cards(shiny::isolate(rv$level))
      self$log(tr("Pulled a golden Lucky Card!"))
    }
    ap <- album_progress(owned)
    newly <- setdiff(ap$complete_sets, shiny::isolate(rv$sets_claimed))
    if (length(newly)) self$toast(tr("Set complete!"), tr("%s - claim your prize in the Cougar Album", tr(ALBUM_SETS$name[newly[1]])), kind = "success", icon = "\U0001F3C6")
    invisible(p)
  }

  self$claim_set <- function(set) {
    set <- as.integer(set)
    ap <- album_progress(shiny::isolate(rv$album))
    if (!(set %in% ap$complete_sets) || set %in% shiny::isolate(rv$sets_claimed)) return(FALSE)
    rv$sets_claimed <- c(shiny::isolate(rv$sets_claimed), set)
    amt <- ALBUM_SETS$reward[set]
    self$credit(amt)
    self$celebrate("album", amt, tr("SET COMPLETE!"), tr(ALBUM_SETS$name[set]))
    self$log(tr("Completed set %s (+%s)", tr(ALBUM_SETS$name[set]), fmt_coins(amt)))
    TRUE
  }

  self$claim_album <- function() {
    ap <- album_progress(shiny::isolate(rv$album))
    if (ap$have < ap$total || shiny::isolate(rv$album_claimed)) return(FALSE)
    rv$album_claimed <- TRUE
    self$credit(ALBUM_COMPLETE_REWARD)
    self$celebrate("album", ALBUM_COMPLETE_REWARD, tr("ALBUM COMPLETE!"), tr("You're playing Like a Pro"))
    TRUE
  }

  self$trade_spares <- function() {
    owned <- shiny::isolate(rv$album)
    v <- spare_value(owned)
    if (v <= 0) return(0)
    owned[] <- pmin(owned, 1L)
    rv$album <- owned
    rv$stars <- shiny::isolate(rv$stars) + v
    self$toast(tr("Spares traded"), tr("+%s \u2B50 stars added to your Star Market balance", fmt_coins(v)), kind = "success", icon = "\u2B50")
    v
  }

  # Resolve a finished Lucky Cards bonus.
  self$settle_lucky <- function(b) {
    i <- b$chosen
    kind <- b$tiles$kind[i]; val <- b$tiles$value[i]
    if (kind == "coins") { self$credit(val); self$celebrate("win", val, tr("LUCKY CARDS!"), tr("Coin prize")) }
    if (kind == "stars") { rv$stars <- shiny::isolate(rv$stars) + val; self$toast(tr("Lucky Cards"), tr("+%d stars", as.integer(val)), "success", "\u2B50") }
    if (kind == "pack") self$award_pack(b$tiers[i], "Lucky Cards")
    rv$lucky <- NULL
  }

  # ---- Star Market ---------------------------------------------------------------------------
  self$buy <- function(item_id) {
    it <- MARKET_ITEMS[MARKET_ITEMS$id == item_id, ]
    if (!nrow(it)) return(FALSE)
    if (it$kind == "avatar" && it$value %in% shiny::isolate(rv$avatars)) {
      rv$avatar <- it$value; return(TRUE)
    }
    if (shiny::isolate(rv$stars) < it$price) {
      self$toast(tr("Not enough stars"), tr("Trade spare cards or complete Lucky Cards to earn stars."), "warning", "\u2B50")
      return(FALSE)
    }
    rv$stars <- shiny::isolate(rv$stars) - it$price
    switch(it$kind,
      coins = { self$credit(as.numeric(it$value)); self$celebrate("win", as.numeric(it$value), tr("COIN CHEST!")) },
      pack = self$award_pack(it$value, "Star Market"),
      boost = {
        b <- shiny::isolate(rv$boosts); parts <- strsplit(it$value, ":")[[1]]
        b[[parts[1]]] <- (b[[parts[1]]] %||% 0L) + as.integer(parts[2]); rv$boosts <- b
        self$toast(tr(it$name), tr(it$desc), "success", it$icon)
      },
      wheel = { rv$wheel_hourly_at <- 0; self$toast(tr("Wheel recharged!"), tr("Your hourly Wheel of Fun is ready."), "success", "\U0001F3A1") },
      avatar = {
        rv$avatars <- unique(c(shiny::isolate(rv$avatars), it$value)); rv$avatar <- it$value
        self$toast(tr("New avatar!"), tr("%s is now your avatar.", tr(it$name)), "success", it$icon)
      })
    self$log(tr("Star Market: bought %s", tr(it$name)))
    TRUE
  }

  self$set_avatar <- function(a) {
    if (a %in% shiny::isolate(rv$avatars)) rv$avatar <- a
  }

  # ---- Wheel of Fun -----------------------------------------------------------------------
  self$wheel_status <- function(now = Sys.time()) {
    last <- rv$wheel_hourly_at
    wait <- max(0, WHEEL_HOURLY_SECS - (as.numeric(now) - last))
    today <- period_keys(now)$day
    list(hourly_ready = wait <= 0, hourly_wait = wait,
         daily_ready = !identical(rv$wheel_daily_on, today),
         daily_wait = secs_until("day", now))
  }
  self$spin_wheel <- function(daily = FALSE) {
    st <- shiny::isolate(self$wheel_status())
    if (daily && !st$daily_ready) return(NULL)
    if (!daily && !st$hourly_ready) return(NULL)
    vip <- VIP_TIERS$wheel_bonus[vip_index(shiny::isolate(rv$vip_points))]
    res <- spin_fun_wheel(daily = daily, vip_bonus = vip)
    if (daily) rv$wheel_daily_on <- period_keys()$day else rv$wheel_hourly_at <- now_secs()
    self$credit(res$total)
    self$log(if (daily) tr("Wheel of Fun (daily): +%s", fmt_coins(res$total)) else tr("Wheel of Fun: +%s", fmt_coins(res$total)))
    res
  }

  # ---- Playtika Rewards ------------------------------------------------------------------------
  self$vip <- function() {
    p <- rv$vip_points
    i <- vip_index(p)
    nxt <- if (i < nrow(VIP_TIERS)) VIP_TIERS$min_points[i + 1] else NA
    list(index = i, tier = VIP_TIERS$tier[i], points = p, next_at = nxt,
         pct = if (is.na(nxt)) 100 else 100 * (p - VIP_TIERS$min_points[i]) / (nxt - VIP_TIERS$min_points[i]))
  }
  self$claim_vip_gift <- function() {
    today <- period_keys()$day
    if (identical(shiny::isolate(rv$vip_gift_on), today)) return(FALSE)
    i <- vip_index(shiny::isolate(rv$vip_points))
    amt <- VIP_TIERS$daily_gift[i]
    rv$vip_gift_on <- today
    self$credit(amt)
    self$celebrate("win", amt, tr("STATUS GIFT"), tr("%s daily gift", tr(VIP_TIERS$tier[i])))
    TRUE
  }

  # ---- Daily Dash ----------------------------------------------------------------------------------
  self$dash_board <- function(now = Sys.time()) {
    keys <- period_keys(now)
    prog <- rv$dash; claimed <- rv$dash_claimed
    lapply(c("day", "week", "month"), function(per) {
      m <- dash_missions(per, keys[[per]])
      m$progress <- vapply(m$id, function(i) min(prog[[i]] %||% 0, m$target[m$id == i]), 0)
      m$done <- m$progress >= m$target
      m$claimed <- m$id %in% claimed
      chest_id <- paste("chest", per, keys[[per]], sep = "|")
      list(period = per, key = keys[[per]], missions = m, chest_id = chest_id,
           chest_ready = all(m$claimed) && !(chest_id %in% claimed),
           chest_claimed = chest_id %in% claimed,
           resets_in = secs_until(per, now))
    })
  }
  self$dash_claim <- function(id) {
    board <- shiny::isolate(self$dash_board())
    for (b in board) {
      m <- b$missions
      if (id %in% m$id) {
        i <- which(m$id == id)
        if (!m$done[i] || m$claimed[i]) return(FALSE)
        rv$dash_claimed <- c(shiny::isolate(rv$dash_claimed), id)
        amt <- DASH_REWARD[[b$period]]$mission
        self$credit(amt)
        rv$stars <- shiny::isolate(rv$stars) + DASH_REWARD[[b$period]]$points / 10
        self$toast(tr("Mission complete!"), tr("%s: +%s coins", m$text[i], fmt_coins(amt)), "success", "\U0001F3C1")
        return(TRUE)
      }
      if (identical(id, b$chest_id) && b$chest_ready) {
        rv$dash_claimed <- c(shiny::isolate(rv$dash_claimed), id)
        r <- DASH_REWARD[[b$period]]
        self$credit(r$chest)
        self$celebrate("album", r$chest, tr("DASH CHEST!"), tr(c(day = "Daily pass complete", week = "Weekly pass complete", month = "Monthly pass complete")[[b$period]]))
        self$award_pack(r$pack, "Daily Dash")
        return(TRUE)
      }
    }
    FALSE
  }

  # ---- Monsterpedia -----------------------------------------------------------------------------------
  self$monster_board <- function() {
    prog <- rv$monster; claimed <- rv$monster_claimed
    done_prev <- TRUE
    lapply(MONSTER_CHAPTERS, function(ch) {
      cc <- MONSTER_CHALLENGES[MONSTER_CHALLENGES$chapter == ch$id, ]
      key <- paste(ch$id, seq_len(nrow(cc)), sep = ".")
      cc$progress <- vapply(seq_along(key), function(i) min(prog[[key[i]]] %||% 0, cc$target[i]), 0)
      cc$captured <- cc$progress >= cc$target
      cc$text <- mapply(monster_challenge_text, cc$metric, cc$target)
      unlocked <- done_prev
      complete <- all(cc$captured)
      done_prev <<- complete && (ch$id %in% claimed)
      list(chapter = ch, challenges = cc, unlocked = unlocked, complete = complete,
           claimed = ch$id %in% claimed)
    })
  }
  self$monster_claim <- function(chapter_id) {
    board <- shiny::isolate(self$monster_board())
    for (b in board) if (b$chapter$id == chapter_id && b$complete && b$unlocked && !b$claimed) {
      rv$monster_claimed <- c(shiny::isolate(rv$monster_claimed), chapter_id)
      self$credit(b$chapter$reward)
      rv$avatars <- unique(c(shiny::isolate(rv$avatars), b$chapter$avatar))
      self$celebrate("album", b$chapter$reward, tr("CHAPTER CLEARED!"), tr("%s - exclusive avatar unlocked", tr(b$chapter$name)))
      self$award_pack("gold", "Monsterpedia")
      return(TRUE)
    }
    FALSE
  }

  # ---- The central event hook ------------------------------------------------------------------------
  # Record a finished play.
  # @param family "slots" | "blackjack" | "poker" | "roulette" | "side"
  # @param game game id (slot id, variant id...)
  # @param category slot category (classic/myth/animal) or NULL
  # @param wager coins staked (0 for free spins)
  # @param win coins returned/won
  # @param bet reference bet size for multiples (defaults to wager)
  # @param events character tags (slot features, etc.)
  # @param metrics named numeric extra Daily Dash metric increments
  self$record <- function(family, game, category = NULL, wager = 0, win = 0, bet = wager,
                          events = character(0), metrics = NULL) {
    shiny::isolate({
      # player statistics (balance after the play, before any level-up reward)
      cat <- stat_category(family, category)
      balance <- rv$coins
      rv$track <- track_add(rv$track, now_secs(), balance, wager, win, cat, stat_is_risky(family, game))
      if (!is.null(ident$id)) store$log_play(ident$id, family, game, wager, win, balance = balance, category = cat)
      bet <- if (is.null(bet) || bet <= 0) max(wager, 1) else bet
      # stats
      st <- rv$stats
      st$plays <- st$plays + 1; st$wagered <- st$wagered + wager; st$won <- st$won + win
      if (family == "slots") st$spins <- st$spins + 1 else st$hands <- st$hands + 1
      if (win > st$biggest) { st$biggest <- win; st$biggest_game <- game }
      rv$stats <- st

      # XP & levels
      b <- rv$boosts
      xp_gain <- (wager / 50 + if (wager > 0) 5 else 1)
      if ((b$xp2 %||% 0) > 0 && wager > 0) { xp_gain <- xp_gain * 2; b$xp2 <- b$xp2 - 1L; rv$boosts <- b }
      xp <- rv$xp + xp_gain; lvl <- rv$level
      while (xp >= xp_needed(lvl)) {
        xp <- xp - xp_needed(lvl); lvl <- lvl + 1L
        reward <- level_reward(lvl)
        rv$coins <- rv$coins + reward
        self$celebrate("level", reward, tr("LEVEL %d!", lvl),
                       if (max_bet_index(lvl) > max_bet_index(lvl - 1L))
                         tr("Max bet unlocked: %s", fmt_coins(BET_LADDER[max_bet_index(lvl)])) else tr("Level up bonus"))
        self$log(tr("Reached level %d", lvl))
        if (lvl %% 5 == 0) self$award_pack("gold", tr("Level %d", lvl))
      }
      rv$xp <- xp; rv$level <- lvl

      # Playtika Rewards
      if (wager > 0) {
        old_i <- vip_index(rv$vip_points)
        pts <- loyalty_points(wager)
        rv$vip_points <- rv$vip_points + pts
        vf <- rv$vip_by_family; vf[[family]] <- (vf[[family]] %||% 0) + pts; rv$vip_by_family <- vf
        new_i <- vip_index(rv$vip_points)
        if (new_i > old_i) self$celebrate("vip", 0, tr("%s STATUS!", toupper(tr(VIP_TIERS$tier[new_i]))),
                                          tr("Wheel bonus +%d%%, daily gift %s", as.integer(round(100 * VIP_TIERS$wheel_bonus[new_i])), fmt_coins(VIP_TIERS$daily_gift[new_i])))
      }

      # Card drops
      if (wager > 0 && stats::runif(1) < PACK_DROP_CHANCE) self$award_pack(drop_tier(bet), "lucky drop")

      # Daily Dash metrics
      inc <- c(wager = wager, win_x = if (bet > 0) win / bet else 0)
      if (family == "slots") {
        inc <- c(inc, spins = 1, big_wins = as.numeric(win >= 8 * bet),
                 features = as.numeric(any(events %in% c("bonus", "free_spins", "feature", "hold_spin", "jackpot"))))
        if (!is.null(category)) inc[paste0("spins_", category)] <- 1
      }
      if (!is.null(metrics)) inc <- c(inc, metrics)
      inc <- inc[inc > 0]
      if (length(inc)) {
        keys <- period_keys()
        dash <- rv$dash
        for (per in c("day", "week", "month")) {
          m <- dash_missions(per, keys[[per]])
          for (i in seq_len(nrow(m))) {
            if (m$metric[i] %in% names(inc))
              dash[[m$id[i]]] <- (dash[[m$id[i]]] %||% 0) + unname(inc[[m$metric[i]]])
          }
        }
        rv$dash <- dash
      }

      # Monsterpedia
      ch <- Filter(function(c) c$game == game, MONSTER_CHAPTERS)
      if (length(ch)) {
        ch <- ch[[1]]
        board <- self$monster_board()
        cb <- Filter(function(x) x$chapter$id == ch$id, board)[[1]]
        if (cb$unlocked && !cb$claimed) {
          mon <- rv$monster
          cc <- MONSTER_CHALLENGES[MONSTER_CHALLENGES$chapter == ch$id, ]
          x <- if (bet > 0) win / bet else 0
          for (i in seq_len(nrow(cc))) {
            key <- paste(ch$id, i, sep = ".")
            before <- mon[[key]] %||% 0
            met <- cc$metric[i]
            add <- if (met == "spins") 1
              else if (met == "win_x") x
              else if (met == "single_x") (if (x >= cc$target[i]) cc$target[i] else 0)
              else if (startsWith(met, "event:")) as.numeric(sub("event:", "", met) %in% events)
              else 0
            if (add > 0) {
              mon[[key]] <- before + add
              if (before < cc$target[i] && before + add >= cc$target[i])
                self$toast(tr("Monster captured!"), paste(cc$glyph[i], tr("%s joins your Monsterpedia", tr(cc$monster[i]))), "monster", cc$glyph[i])
            }
          }
          rv$monster <- mon
        }
      }
    })
    invisible(NULL)
  }

  # ---- persistence ----------------------------------------------------------------------------------
  self$snapshot <- function() {
    list(v = SAVE_VERSION, coins = rv$coins, xp = rv$xp, level = rv$level, stars = rv$stars,
         vip_points = rv$vip_points, vip_by_family = as.list(rv$vip_by_family),
         album = as.list(rv$album), sets_claimed = as.list(rv$sets_claimed), album_claimed = rv$album_claimed,
         avatar = rv$avatar, avatars = as.list(rv$avatars), boosts = rv$boosts,
         wheel_hourly_at = rv$wheel_hourly_at, wheel_daily_on = rv$wheel_daily_on, vip_gift_on = rv$vip_gift_on,
         dash = rv$dash, dash_claimed = as.list(rv$dash_claimed),
         monster = rv$monster, monster_claimed = as.list(rv$monster_claimed),
         stats = rv$stats, game_meta = rv$game_meta, recent_pulls = as.list(rv$recent_pulls),
         name = rv$name, track = track_snapshot(rv$track))
  }

  self$restore <- function(x) {
    if (!is.list(x) || !identical(as.integer(x$v %||% 0), SAVE_VERSION)) return(FALSE)
    num <- function(v, d = 0) { v <- suppressWarnings(as.numeric(v)); if (length(v) != 1 || is.na(v)) d else v }
    chr <- function(v) as.character(unlist(v %||% character(0)))
    named_num <- function(v) { v <- unlist(v); if (is.null(v)) numeric(0) else v }
    keys <- period_keys()
    live <- function(ids) {
      ids <- as.character(ids %||% character(0))
      ids[vapply(strsplit(ids, "|", fixed = TRUE), function(p) length(p) >= 2 && p[length(p) - (if (p[1] == "chest") 0 else 1)] %in% unlist(keys), logical(1))]
    }
    shiny::isolate({
      rv$coins <- max(0, num(x$coins, START_COINS))
      rv$xp <- max(0, num(x$xp)); rv$level <- as.integer(max(1, num(x$level, 1)))
      rv$stars <- max(0, num(x$stars)); rv$vip_points <- max(0, num(x$vip_points))
      vf <- named_num(x$vip_by_family); base <- rv$vip_by_family
      base[intersect(names(vf), names(base))] <- vf[intersect(names(vf), names(base))]; rv$vip_by_family <- base
      al <- named_num(x$album); al <- al[names(al) %in% ALBUM_CARDS$id]
      rv$album <- stats::setNames(as.integer(al), names(al))
      rv$sets_claimed <- as.integer(unlist(x$sets_claimed))
      rv$album_claimed <- isTRUE(x$album_claimed)
      av <- chr(x$avatars); rv$avatars <- unique(c(DEFAULT_AVATAR, av))
      rv$avatar <- if (isTRUE(x$avatar %in% rv$avatars)) x$avatar else DEFAULT_AVATAR
      rv$boosts <- list(xp2 = as.integer(num(x$boosts$xp2)), win20 = as.integer(num(x$boosts$win20)))
      rv$wheel_hourly_at <- num(x$wheel_hourly_at); rv$wheel_daily_on <- as.character(x$wheel_daily_on %||% "")
      rv$vip_gift_on <- as.character(x$vip_gift_on %||% "")
      d <- x$dash %||% list(); d <- d[live(names(d))]; rv$dash <- lapply(d, num)
      rv$dash_claimed <- live(chr(x$dash_claimed))
      rv$monster <- lapply(x$monster %||% list(), num)
      rv$monster_claimed <- chr(x$monster_claimed)
      s <- x$stats %||% list(); st <- rv$stats
      for (k in names(st)) if (!is.null(s[[k]])) st[[k]] <- if (is.character(st[[k]])) as.character(s[[k]]) else num(s[[k]])
      rv$stats <- st
      rv$game_meta <- lapply(x$game_meta %||% list(), function(g) lapply(g, num))
      rv$recent_pulls <- intersect(chr(x$recent_pulls), ALBUM_CARDS$id)
      nm <- chr(x$name)
      rv$name <- if (length(nm) == 1 && fc_valid_name(nm)) nm else ""
      rv$track <- track_restore(x$track)
    })
    TRUE
  }

  self$reset <- function() {
    shiny::isolate({
      rv$coins <- START_COINS; rv$xp <- 0; rv$level <- 1L; rv$stars <- 25; rv$vip_points <- 0
      vf <- rv$vip_by_family; vf[] <- 0; rv$vip_by_family <- vf; rv$album <- integer(0); rv$sets_claimed <- integer(0)
      rv$album_claimed <- FALSE; rv$avatar <- DEFAULT_AVATAR; rv$avatars <- DEFAULT_AVATAR
      rv$boosts <- list(xp2 = 0L, win20 = 0L); rv$wheel_hourly_at <- 0; rv$wheel_daily_on <- ""
      rv$vip_gift_on <- ""; rv$dash <- list(); rv$dash_claimed <- character(0)
      rv$monster <- list(); rv$monster_claimed <- character(0)
      rv$stats <- list(plays = 0, wagered = 0, won = 0, biggest = 0, biggest_game = "", packs = 0, spins = 0, hands = 0)
      rv$game_meta <- list(); rv$recent_pulls <- character(0); rv$feed <- character(0)
      rv$track <- track_new()
    })
    if (!is.null(ident$session)) self$session_begin()
  }

  self
}

# ---- Linked progressive jackpots (shared by ALL sessions) ------------------------------------
.linked_env <- new.env(parent = emptyenv())

# Server-wide reactive pool for Bank of Jackpots. Created lazily once per R
# process, so every connected player feeds (and can win) the same pots.
# With a server-side store the pots are loaded from (and saved to) the
# database, so they survive app restarts.
linked_jackpots <- function(store = fc_storage("browser")) {
  if (is.null(.linked_env$rv)) {
    pots <- store$load_jackpots() %||% JACKPOT_SEEDS
    .linked_env$rv <- shiny::reactiveValues(pots = pots, last = NULL, contributions = 0)
    .linked_env$store <- store
  }
  .linked_env$rv
}

# Persist the linked pots (called after every change).
linked_jackpots_save <- function(pots) {
  st <- .linked_env$store
  if (!is.null(st)) st$save_jackpots(pots)
  invisible(pots)
}

# Forget the in-memory pool (tests).
linked_jackpots_reset <- function() {
  .linked_env$rv <- NULL; .linked_env$store <- NULL
  invisible(NULL)
}
