# ---------------------------------------------------------------------------
# Build the static website (GitHub Pages, Netlify, Cloudflare Pages, any static
# host) with Shinylive: the whole casino runs in the visitor's browser on webR
# (R compiled to WebAssembly), so no R server is needed and hosting is free.
#
#   install.packages(c("shinylive", "bslib", "shiny"))
#   Rscript --no-init-file tools/build_site.R              # -> _site/
#   Rscript --no-init-file tools/build_site.R docs         # -> docs/ (GitHub Pages "from a branch")
#   Rscript --no-init-file tools/build_site.R _site --app-only   # only the app folder
#
# Preview locally:  httpuv::runStaticServer("_site")   (browsers need http://,
# opening index.html from disk does not work).
#
# Do NOT run shinylive::export(".", "docs") on this folder: it would pack the
# whole repository (videos, renv library, tests...) into a 120+ MB app.json
# that GitHub rejects and every visitor downloads. This script exports only
# what the app needs (about 0.5 MB of app files).
#
# What makes the browser build start fast:
#   * only the app sources and assets are exported (no tests/tools/media);
#   * the app sources its R files directly (no pkgload, no extra packages);
#   * the Bootstrap theme is compiled here, once, so the browser does not run
#     Sass (the page uses bslib's precompiled default theme + this CSS).
# Each visitor's progress is saved in their browser (localStorage), like
# storage = "browser". Shared-database features (leaderboard, community
# clusters, jackpots shared between players) need a real R server, see DEPLOY.md.
# ---------------------------------------------------------------------------

args <- commandArgs(trailingOnly = TRUE)
out <- if (length(args) && !startsWith(args[1], "--")) args[1] else "_site"
app_only <- "--app-only" %in% args

if (!file.exists("DESCRIPTION") || !dir.exists("R"))
  stop("Run this from the fortuneCougar folder (the one with DESCRIPTION).", call. = FALSE)

# ---- 1. a self-contained app folder ------------------------------------------------
app <- if (app_only) out else file.path(tempdir(), "fortuneCougar-app")
unlink(app, recursive = TRUE)
dir.create(file.path(app, "src"), recursive = TRUE)
dir.create(file.path(app, "www", "fc-assets"), recursive = TRUE)

src <- sort(list.files("R", pattern = "^[A-Za-z0-9].*\\.[Rr]$", full.names = TRUE))
stopifnot(all(file.copy(src, file.path(app, "src"))))
# www/fc-assets/: served at fc-assets/ by Shiny's www folder and by addResourcePath()
www <- list.files(file.path("inst", "app", "www"), full.names = TRUE)
stopifnot(all(file.copy(www, file.path(app, "www", "fc-assets"))))

# ---- 2. the theme, compiled once here instead of in every visitor's browser ----------
precompile_theme <- function(dest) {
  tryCatch({
    suppressPackageStartupMessages({ library(shiny); library(bslib) })
    env <- new.env(parent = globalenv())
    for (f in src) sys.source(f, envir = env, keep.source = FALSE)
    deps <- bslib::bs_theme_dependencies(env$fc_theme())
    bs <- Filter(function(d) identical(d$name, "bootstrap"), deps)[[1]]
    dir <- bs$src$file %||% bs$src[["file"]]
    css <- list.files(dir, pattern = "\\.css$", full.names = TRUE, recursive = TRUE)
    css <- css[which.max(file.size(css))]                     # the compiled Bootstrap + bslib CSS
    stopifnot(length(css) == 1, file.size(css) > 50000)
    file.copy(css, dest, overwrite = TRUE)
  }, error = function(e) {
    message("Note: the theme was not precompiled (", conditionMessage(e), "); the browser will compile it.")
    FALSE
  })
}
`%||%` <- function(x, y) if (is.null(x)) y else x
theme_ok <- isTRUE(precompile_theme(file.path(app, "www", "fc-assets", "fc-theme.css")))

writeLines(c(
  "# fortuneCougar in the browser (Shinylive / webR). Generated by tools/build_site.R:",
  "# edit the package sources, not this file.",
  "library(shiny)",
  "library(bslib)",
  "library(htmltools)",
  "library(jsonlite)",
  "for (f in sort(list.files(\"src\", pattern = \"\\\\.[Rr]$\", full.names = TRUE))) source(f, local = TRUE)",
  "",
  "# no R server, no database: progress is saved in the visitor's browser",
  "options(fortuneCougar.storage = \"browser\", fortuneCougar.lang = \"en\")",
  "fc_assets_dir <- function() normalizePath(file.path(\"www\", \"fc-assets\"))",
  "",
  "# the casino theme was compiled when the site was built: use bslib's precompiled",
  "# default theme (no Sass in the browser) and load the compiled casino theme on top",
  "if (file.exists(file.path(\"www\", \"fc-assets\", \"fc-theme.css\"))) {",
  "  fc_theme <- function() bslib::bs_theme(version = 5)",
  "  options(fortuneCougar.extra_css = \"fc-assets/fc-theme.css\")",
  "}",
  "",
  "shinyApp(fc_app_ui, fc_app_server)"
), file.path(app, "app.R"))

size_mb <- function(path) sum(file.size(list.files(path, recursive = TRUE, full.names = TRUE, all.files = TRUE))) / 2^20

if (app_only) {
  message(sprintf("App folder written to %s (%.1f MB, theme %s)\nRun it with shiny::runApp(\"%s\")",
                  normalizePath(app), size_mb(app), if (theme_ok) "precompiled" else "compiled at run time", app))
} else {
  # ---- 3. export it as a static site ---------------------------------------------------
  if (!requireNamespace("shinylive", quietly = TRUE))
    stop("Install the shinylive package first: install.packages(\"shinylive\")", call. = FALSE)
  unlink(out, recursive = TRUE)
  shinylive::export(app, out)
  unlink(app, recursive = TRUE)
  file.create(file.path(out, ".nojekyll"))        # GitHub Pages: serve folders starting with _
  # guard against ever shipping a huge bundle again (GitHub's file limit is 100 MB)
  aj <- file.path(out, "app.json")
  if (file.exists(aj) && file.size(aj) > 5 * 2^20)
    stop(sprintf("%s is %.0f MB: something large was exported. Check the app folder.", aj, file.size(aj) / 2^20), call. = FALSE)
  big <- list.files(out, recursive = TRUE, full.names = TRUE)
  big <- big[file.size(big) > 25 * 2^20]
  if (length(big)) warning("Files over 25 MB (too big for some static hosts): ", paste(big, collapse = ", "), call. = FALSE)
  message(sprintf("Static site written to %s (%.0f MB in total, app.json %.2f MB, theme %s)\nPreview: httpuv::runStaticServer(\"%s\")",
                  normalizePath(out), size_mb(out), file.size(aj) / 2^20,
                  if (theme_ok) "precompiled" else "compiled in the browser", out))
}
